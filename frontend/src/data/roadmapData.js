// Helper to get total topic count for a track
export function getTrackTopicCount(track) {
  if (!track || !track.stages) return 0;
  return track.stages.reduce((acc, stage) => acc + (stage.topics?.length || 0), 0);
}

// Helper to get all topics as flat list for a track
export function getTrackTopics(track) {
  if (!track || !track.stages) return [];
  const list = [];
  track.stages.forEach((stage) => {
    (stage.topics || []).forEach((topic) => {
      list.push({ ...topic, stageId: stage.id, stageTitle: stage.title, stageNumber: stage.stageNumber });
    });
  });
  return list;
}
